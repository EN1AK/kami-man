def build(db_path):
    rules = []
    with sqlite3.connect(db_path.resolve().as_uri() + "?mode=ro", uri=True) as db:
        for label, patterns in FAMILIES.items():
            clauses = " OR ".join("name LIKE ?" for _ in patterns)
            codes = sorted({row[0] for row in db.execute("SELECT id FROM texts WHERE " + clauses, patterns)})
            if codes:
                rules.append({"label": label, "cards": codes, "match": "any"})
    return {"version": 1, "source": "Feature-card mappings built only from a local YGOPro CDB",
            "rules": rules}


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--db", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    data = build(args.db)
    args.out.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Built {len(data['rules'])} deck-name families")
